          public void registrarAccion(String accion) {
    String sql = "INSERT INTO bitacora (usuario, rol, accion) VALUES (?, ?, ?)";
    db.Conexion dbCon = new db.Conexion(); 
    
    try (java.sql.Connection con = dbCon.conectar(); 
         java.sql.PreparedStatement ps = con.prepareStatement(sql)) {
        
        if (con != null) {
            ps.setString(1, this.nombre); 
            ps.setString(2, this.rol);    
            ps.setString(3, accion);
            ps.executeUpdate();
        }
    } catch (java.sql.SQLException e) {
        System.out.println("Error en bitácora: " + e.getMessage());
    }
}
    
    public void ListarUsuarios() {
    List<Usuario> lista = uDao.ListarUsuarios();
    modelo = (DefaultTableModel) tblUsuarios.getModel();
    modelo.setRowCount(0); // Limpia la tabla para que no se dupliquen los datos
    Object[] ob = new Object[5];
    for (int i = 0; i < lista.size(); i++) {
        ob[0] = lista.get(i).getIdUsuario();
        ob[1] = lista.get(i).getNombreCompleto();
        ob[2] = lista.get(i).getUsername();
        ob[3] = lista.get(i).getContrasena();
        ob[4] = lista.get(i).getRol();
        modelo.addRow(ob);
    }
    tblUsuarios.setModel(modelo);
}
    
