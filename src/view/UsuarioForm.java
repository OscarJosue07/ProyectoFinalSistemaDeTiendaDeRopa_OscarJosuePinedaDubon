    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
if (!txtId.getText().isEmpty()) {
    int pregunta = JOptionPane.showConfirmDialog(null, "¿Estás seguro de eliminar este usuario?");
    if (pregunta == 0) {
        int id = Integer.parseInt(txtId.getText());
        uDao.EliminarUsuario(id);
        ListarUsuarios(); // Refresca la tabla
        LimpiarCampos();  // Borra los textos
    }
} else {
    JOptionPane.showMessageDialog(null, "Selecciona un usuario de la tabla");
}
registrarAccion("ELIMINÓ permanentemente al usuario: " + txtUsername.getText());
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
if (!txtUsername.getText().equals("") && !txtContrasena.getText().equals("") && !txtNombre_Completo.getText().equals("")) {
    
    // 1. Llenamos el objeto Usuario con lo que escribiste en los cuadros de texto
    u.setNombreCompleto(txtNombre_Completo.getText());
    u.setUsername(txtUsername.getText());
    u.setContrasena(txtContrasena.getText());
    u.setRol(txtRol.getText());

    // 2. Llamamos al método del DAO para insertar en MySQL
    if (uDao.RegistrarUsuario(u)) {
        JOptionPane.showMessageDialog(null, "¡Usuario Registrado!");
        
        // 3. Limpiamos y actualizamos la tabla para ver el nuevo usuario de una vez
        LimpiarCampos();
        ListarUsuarios(); 
    } else {
        JOptionPane.showMessageDialog(null, "Error al registrar: El usuario ya existe o hay un problema con la base de datos");
    }
} else {
    JOptionPane.showMessageDialog(null, "Por favor, completa todos los campos obligatorios");
}
registrarAccion("Creó un nuevo acceso para el usuario: " + txtUsername.getText());
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificar1ActionPerformed
if (txtId.getText().equals("")) {
    JOptionPane.showMessageDialog(null, "Seleccione una fila de la tabla");
} else {
    if (!txtNombre_Completo.getText().equals("") && !txtUsername.getText().equals("")) {
        u.setNombreCompleto(txtNombre_Completo.getText());
        u.setUsername(txtUsername.getText());
        u.setContrasena(txtContrasena.getText());
        u.setRol(txtRol.getText());
        u.setIdUsuario(Integer.parseInt(txtId.getText()));
        
        if (uDao.ModificarUsuario(u)) {
            JOptionPane.showMessageDialog(null, "Usuario Modificado");
            LimpiarCampos();
            ListarUsuarios(); // Para ver los cambios de inmediato
        } else {
            JOptionPane.showMessageDialog(null, "Error al modificar el usuario");
        }
    }
}
registrarAccion("Actualizó los datos/permisos del usuario: " + txtUsername.getText());
    }//GEN-LAST:event_btnModificar1ActionPerformed

